CREATE TABLE IF NOT EXISTS public.acrogym_scores (
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	student_id integer NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
	inzet smallint NOT NULL CHECK (inzet BETWEEN 1 AND 4),
	techniek smallint NOT NULL CHECK (techniek BETWEEN 1 AND 4),
	ontwerpen smallint NOT NULL CHECK (ontwerpen BETWEEN 1 AND 4),
	created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS acrogym_scores_student_created_at_idx
	ON public.acrogym_scores (student_id, created_at DESC);
